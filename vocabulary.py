def get_vocab_translation(text, target_lang):
    """
    Look up direct translation for single signs or multi-sign combinations.
    """
    if not text:
        return None
    clean = text.strip().upper().replace(" ", "_")
    lang_dict = VOCAB_MAP.get(target_lang, {})
    if clean in lang_dict:
        return lang_dict[clean]

    # Check words combination
    words = clean.split("_")
    translated_parts = []
    all_found = True
    for w in words:
        if w in lang_dict:
            translated_parts.append(lang_dict[w])
        else:
            all_found = False
            break

    if all_found and translated_parts:
        return " ".join(translated_parts)

    return None
